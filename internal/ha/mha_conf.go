// MHAConfOptions 生成 app.cnf 时可调参数（专业默认值，可被覆盖）。
type MHAConfOptions struct {
	ConfPath string `json:"conf_path,omitempty"`

	// [server default]
	User                       string `json:"user,omitempty"`                         // MySQL 管理账号（须可在各节点执行复制/状态查询）
	Password                   string `json:"password,omitempty"`                     // 对应密码；留空则模板写占位
	SSHUser                    string `json:"ssh_user,omitempty"`                     // Manager → 节点 SSH
	SSHPort                    int    `json:"ssh_port,omitempty"`
	SSHOptions                 string `json:"ssh_options,omitempty"`
	ManagerWorkdir             string `json:"manager_workdir,omitempty"`
	ManagerLog                 string `json:"manager_log,omitempty"`
	RemoteWorkdir              string `json:"remote_workdir,omitempty"`
	MasterBinlogDir            string `json:"master_binlog_dir,omitempty"`
	PingInterval               int    `json:"ping_interval,omitempty"`
	SecondaryCheckScript       string `json:"secondary_check_script,omitempty"`
	MasterIPFailoverScript     string `json:"master_ip_failover_script,omitempty"`
	MasterIPOnlineChangeScript string `json:"master_ip_online_change_script,omitempty"`
	ReportScript               string `json:"report_script,omitempty"`
	ShutdownScript             string `json:"shutdown_script,omitempty"`
	CheckReplDelay             *int   `json:"check_repl_delay,omitempty"` // 0/1
	CheckReplDelta             int    `json:"check_repl_delta,omitempty"`

	// 额外自定义行（追加到 [server default]，专家模式）
	ExtraDefaultLines []string `json:"extra_default_lines,omitempty"`
}

// DefaultMHAConfOptions 专业默认值。
func DefaultMHAConfOptions(clusterName string) MHAConfOptions {
	safe := sanitizeMHAName(clusterName)
	if safe == "" {
		safe = "app"
	}
	checkDelay := 1
	return MHAConfOptions{
		ConfPath:         "/etc/mha/" + safe + ".cnf",
		User:             "mha",
		Password:         "",
		SSHUser:          "root",
		SSHPort:          22,
		ManagerWorkdir:   "/var/log/mha/" + safe,
		ManagerLog:       "/var/log/mha/" + safe + "/manager.log",
		RemoteWorkdir:    "/var/log/mha/" + safe,
		MasterBinlogDir:  "/var/lib/mysql",
		PingInterval:     3,
		CheckReplDelay:   &checkDelay,
		CheckReplDelta:   100,
	}
}

func sanitizeMHAName(name string) string {
	var b strings.Builder
	for _, r := range strings.TrimSpace(name) {
		switch {
		case unicode.IsLetter(r) || unicode.IsDigit(r):
			b.WriteRune(unicode.ToLower(r))
		case r == '-' || r == '_':
			b.WriteRune(r)
		case unicode.IsSpace(r):
			b.WriteByte('_')
		}
	}
	s := b.String()
	if len(s) > 48 {
		s = s[:48]
	}
	return s
}

type mhaHostRow struct {
	Hostname        string
	Port            int
	CandidateMaster int
	NoMaster        int
	CheckReplDelay  *int
	Label           string
}

// RenderMHAAppConf 根据 HA 集群成员与选项生成专业 app.cnf。
func RenderMHAAppConf(cluster *store.HACluster, opts MHAConfOptions) (string, error) {
	if cluster == nil {
		return "", fmt.Errorf("集群为空")
	}
	def := DefaultMHAConfOptions(cluster.Name)
	mergeMHAOpts(&opts, def)

	var hosts []mhaHostRow
	for _, m := range cluster.Members {
		if !m.Enabled && m.ID != "" {
			// Enabled=false 跳过；新建时 Enabled 默认 true
		}
		host := strings.TrimSpace(m.Host)
		if host == "" {
			continue
		}
		port := m.Port
		if port <= 0 {
			port = 3306
		}
		row := mhaHostRow{
			Hostname: host,
			Port:     port,
			Label:    firstNonEmptyHA(m.InstanceName, m.InstanceID),
		}
		switch strings.ToLower(strings.TrimSpace(m.Role)) {
		case "primary":
			row.CandidateMaster = 1
		case "replica":
			row.CandidateMaster = 1
		default:
			continue
		}
		hosts = append(hosts, row)
	}
	if len(hosts) < 2 {
		return "", fmt.Errorf("生成 conf 需要至少 2 个有效成员（含 host）")
	}
	// 稳定排序：hostname:port
	sort.SliceStable(hosts, func(i, j int) bool {
		a := fmt.Sprintf("%s:%d", hosts[i].Hostname, hosts[i].Port)
		b := fmt.Sprintf("%s:%d", hosts[j].Hostname, hosts[j].Port)
		return a < b
	})

	var b strings.Builder
	b.WriteString("# Generated by auto-dba HA · MHA app.cnf\n")
	b.WriteString("# Cluster: " + cluster.Name + " (" + cluster.ID + ")\n")
	b.WriteString("# 请确认 user/password/ssh_user 与现场一致；下发前可本地 masterha_check_repl 验证。\n")
	b.WriteString("# 自动 failover 仍由 masterha_manager 托管；平台仅做计划内切换。\n\n")

	b.WriteString("[server default]\n")
	b.WriteString(fmt.Sprintf("user=%s\n", opts.User))
	if strings.TrimSpace(opts.Password) == "" {
		b.WriteString("password=CHANGE_ME\n")
	} else {
		b.WriteString(fmt.Sprintf("password=%s\n", opts.Password))
	}
	b.WriteString(fmt.Sprintf("ssh_user=%s\n", opts.SSHUser))
	if opts.SSHPort > 0 {
		b.WriteString(fmt.Sprintf("ssh_port=%d\n", opts.SSHPort))
	}
	if strings.TrimSpace(opts.SSHOptions) != "" {
		b.WriteString(fmt.Sprintf("ssh_options=%s\n", opts.SSHOptions))
	}
	b.WriteString(fmt.Sprintf("manager_workdir=%s\n", opts.ManagerWorkdir))
	b.WriteString(fmt.Sprintf("manager_log=%s\n", opts.ManagerLog))
	b.WriteString(fmt.Sprintf("remote_workdir=%s\n", opts.RemoteWorkdir))
	b.WriteString(fmt.Sprintf("master_binlog_dir=%s\n", opts.MasterBinlogDir))
	if opts.PingInterval > 0 {
		b.WriteString(fmt.Sprintf("ping_interval=%d\n", opts.PingInterval))
	}
	if opts.CheckReplDelay != nil {
		b.WriteString(fmt.Sprintf("check_repl_delay=%d\n", *opts.CheckReplDelay))
	}
	if opts.CheckReplDelta > 0 {
		b.WriteString(fmt.Sprintf("check_repl_delta=%d\n", opts.CheckReplDelta))
	}
	writeOptScript(&b, "secondary_check_script", opts.SecondaryCheckScript)
	writeOptScript(&b, "master_ip_failover_script", opts.MasterIPFailoverScript)
	writeOptScript(&b, "master_ip_online_change_script", opts.MasterIPOnlineChangeScript)
	writeOptScript(&b, "report_script", opts.ReportScript)
	writeOptScript(&b, "shutdown_script", opts.ShutdownScript)
	for _, line := range opts.ExtraDefaultLines {
		line = strings.TrimSpace(line)
		if line == "" || strings.HasPrefix(line, "#") {
			b.WriteString(line + "\n")
			continue
		}
		b.WriteString(line + "\n")
	}
	b.WriteString("\n")

	for i, h := range hosts {
		sec := fmt.Sprintf("server%d", i+1)
		b.WriteString(fmt.Sprintf("# %s\n", h.Label))
		b.WriteString(fmt.Sprintf("[%s]\n", sec))
		b.WriteString(fmt.Sprintf("hostname=%s\n", h.Hostname))
		b.WriteString(fmt.Sprintf("port=%d\n", h.Port))
		if h.CandidateMaster == 1 {
			b.WriteString("candidate_master=1\n")
		}
		if h.NoMaster == 1 {
			b.WriteString("no_master=1\n")
		}
		b.WriteString("\n")
	}
	return b.String(), nil
}

func writeOptScript(b *strings.Builder, key, val string) {
	val = strings.TrimSpace(val)
	if val == "" {
		b.WriteString("# " + key + "=\n")
		return
	}
	b.WriteString(fmt.Sprintf("%s=%s\n", key, val))
}

func mergeMHAOpts(dst *MHAConfOptions, def MHAConfOptions) {
	if dst == nil {
		return
	}
	if strings.TrimSpace(dst.ConfPath) == "" {
		dst.ConfPath = def.ConfPath
	}
	if strings.TrimSpace(dst.User) == "" {
		dst.User = def.User
	}
	if strings.TrimSpace(dst.SSHUser) == "" {
		dst.SSHUser = def.SSHUser
	}
	if dst.SSHPort <= 0 {
		dst.SSHPort = def.SSHPort
	}
	if strings.TrimSpace(dst.ManagerWorkdir) == "" {
		dst.ManagerWorkdir = def.ManagerWorkdir
	}
	if strings.TrimSpace(dst.ManagerLog) == "" {
		dst.ManagerLog = def.ManagerLog
	}
	if strings.TrimSpace(dst.RemoteWorkdir) == "" {
		dst.RemoteWorkdir = def.RemoteWorkdir
	}
	if strings.TrimSpace(dst.MasterBinlogDir) == "" {
		dst.MasterBinlogDir = def.MasterBinlogDir
	}
	if dst.PingInterval <= 0 {
		dst.PingInterval = def.PingInterval
	}
	if dst.CheckReplDelay == nil {
		dst.CheckReplDelay = def.CheckReplDelay
	}
	if dst.CheckReplDelta <= 0 {
		dst.CheckReplDelta = def.CheckReplDelta
	}
}
