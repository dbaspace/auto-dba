// BuildSchemaFixSQL 以左侧为源、右侧为目标，为差异项生成只增不删的修复 SQL。
// 返回整份脚本，并把每表脚本写回 items[i].FixSQL。
func BuildSchemaFixSQL(ctx context.Context, left *sql.DB, engine, leftSchema, rightSchema string, items []TableSchemaDiff) (string, error) {
	engine = store.NormalizeDBType(engine)
	if engine == "postgres" {
		leftSchema = firstNonEmpty(leftSchema, "public")
		rightSchema = firstNonEmpty(rightSchema, "public")
	}
	var all strings.Builder
	all.WriteString("-- auto-dba schema compare fix SQL\n")
	all.WriteString("-- 源端(左) → 目标端(右)；仅生成新增/对齐类语句，请人工审核后执行\n\n")
	stmtCount := 0
	for i := range items {
		sqlText, err := buildFixSQLForTable(ctx, left, engine, leftSchema, rightSchema, &items[i])
		if err != nil {
			items[i].FixSQL = "-- 生成失败: " + err.Error() + "\n"
			all.WriteString("-- === " + items[i].Table + " ===\n")
			all.WriteString(items[i].FixSQL)
			all.WriteString("\n")
			continue
		}
		items[i].FixSQL = sqlText
		if strings.TrimSpace(sqlText) == "" {
			continue
		}
		all.WriteString("-- === " + items[i].Table + " ===\n")
		all.WriteString(sqlText)
		if !strings.HasSuffix(sqlText, "\n") {
			all.WriteByte('\n')
		}
		all.WriteByte('\n')
		stmtCount++
	}
	if stmtCount == 0 {
		all.WriteString("-- 无需生成修复 SQL\n")
	}
	return all.String(), nil
}

func buildFixSQLForTable(ctx context.Context, left *sql.DB, engine, leftSchema, rightSchema string, item *TableSchemaDiff) (string, error) {
	eng, err := selectSchemaEngine(engine)
	if err != nil {
		return "", err
	}
	switch item.Status {
	case "match":
		return "", nil
	case "right_only":
		return "-- 仅目标端存在，跳过（不生成 DROP）\n", nil
	case "left_only":
		if eng.IsRoutineVirtualTable(item.Table) {
			return "", nil
		}
		return eng.BuildCreateSQL(ctx, left, leftSchema, rightSchema, item.Table)
	case "differ":
		if eng.IsRoutineVirtualTable(item.Table) {
			return eng.BuildRoutineFixSQL(ctx, left, leftSchema, rightSchema, item)
		}
		return eng.BuildAlterSQL(ctx, left, leftSchema, rightSchema, item)
	default:
		return "", nil
	}
}

func buildPGCreateTableSQL(ctx context.Context, src *sql.DB, ss, ts, table string) (string, error) {
	info, err := fetchPGTableSchemaInfo(ctx, src, ss, table)
	if err != nil {
		return "", err
	}
	var cols []string
	var seqAfter []string
	for _, c := range info.Columns {
		part := quoteIdent("postgres", c.Name) + " " + c.DataType
		if c.NotNull {
			part += " NOT NULL"
		}
		switch c.Identity {
		case "a":
			part += " GENERATED ALWAYS AS IDENTITY"
		case "d":
			part += " GENERATED BY DEFAULT AS IDENTITY"
		default:
			if c.Default != "" {
				if seqSQL, remDefault := pgSequenceBootstrapSQL(ss, ts, table, c.Name, c.Default); len(seqSQL) > 0 {
					seqAfter = append(seqAfter, seqSQL...)
					if remDefault != "" {
						part += " DEFAULT " + remDefault
					}
				} else {
					part += " DEFAULT " + rewriteNextvalSchema(c.Default, ss, ts)
				}
			}
		}
		cols = append(cols, part)
	}
	if len(cols) == 0 {
		return "", fmt.Errorf("源表 %s.%s 无列", ss, table)
	}
	pk, _ := pgPrimaryKey(ctx, src, ss, table)
	if pk != "" {
		cols = append(cols, pk)
	}
	ref := tableRef("postgres", ts, table)
	var b strings.Builder
	b.WriteString(fmt.Sprintf("CREATE SCHEMA IF NOT EXISTS %s;\n", quoteIdent("postgres", ts)))
	b.WriteString(fmt.Sprintf("CREATE TABLE %s (%s);\n", ref, strings.Join(cols, ", ")))
	for _, s := range seqAfter {
		b.WriteString(s)
	}

	for _, c := range info.Constraints {
		if c.Type == "p" || c.Type == "f" {
			continue
		}
		def := strings.TrimSpace(c.Def)
		if def == "" {
			continue
		}
		b.WriteString(fmt.Sprintf("ALTER TABLE %s ADD CONSTRAINT %s %s;\n",
			ref, quoteIdent("postgres", c.Name), def))
	}
	for _, fk := range info.ForeignKeys {
		def := strings.TrimSpace(fk.Def)
		if def == "" {
			continue
		}
		b.WriteString(fmt.Sprintf("ALTER TABLE %s ADD CONSTRAINT %s %s;\n",
			ref, quoteIdent("postgres", fk.Name), def))
	}
	for _, idx := range info.Indexes {
		rewritten := rewritePGIndexDef(idx.Def, ss, table, ts, table)
		if rewritten != "" {
			b.WriteString(ensureSemi(rewritten) + "\n")
		}
	}
	appendPGCommentsRLSTriggers(ctx, src, ss, ts, table, info, &b)
	return b.String(), nil
}

func appendPGCommentsRLSTriggers(ctx context.Context, src *sql.DB, ss, ts, table string, info *pgTableSchemaInfo, b *strings.Builder) {
	ref := tableRef("postgres", ts, table)
	if strings.TrimSpace(info.TableComment) != "" {
		b.WriteString(fmt.Sprintf("COMMENT ON TABLE %s IS %s;\n", ref, quotePGString(info.TableComment)))
	}
	for _, c := range info.Columns {
		if strings.TrimSpace(c.Comment) == "" {
			continue
		}
		b.WriteString(fmt.Sprintf("COMMENT ON COLUMN %s.%s IS %s;\n",
			ref, quoteIdent("postgres", c.Name), quotePGString(c.Comment)))
	}
	if info.RowSecurity {
		b.WriteString(fmt.Sprintf("ALTER TABLE %s ENABLE ROW LEVEL SECURITY;\n", ref))
	}
	if info.ForceRowSecurity {
		b.WriteString(fmt.Sprintf("ALTER TABLE %s FORCE ROW LEVEL SECURITY;\n", ref))
	}
	for _, p := range info.Policies {
		b.WriteString(buildPGCreatePolicySQL(ref, p))
	}
	emittedFn := map[string]struct{}{}
	for _, t := range info.Triggers {
		if fnSQL, fnKey, err := fetchTriggerFunctionSQL(ctx, src, ss, ts, t.Def); err == nil && fnSQL != "" {
			if _, ok := emittedFn[fnKey]; !ok {
				b.WriteString(fnSQL)
				if !strings.HasSuffix(fnSQL, "\n") {
					b.WriteByte('\n')
				}
				emittedFn[fnKey] = struct{}{}
			}
		}
		rewritten := rewritePGTriggerDef(t.Def, ss, table, ts, table)
		if rewritten != "" {
			b.WriteString(ensureSemi(rewritten) + "\n")
		}
		if t.Enabled == "D" {
			b.WriteString(fmt.Sprintf("ALTER TABLE %s DISABLE TRIGGER %s;\n", ref, quoteIdent("postgres", t.Name)))
		}
	}
}

func rewritePGIndexDef(def, ss, st, ts, tt string) string {
	srcOn := []string{
		`ON "` + ss + `"."` + st + `"`,
		`ON ` + ss + `."` + st + `"`,
		`ON "` + ss + `".` + st,
		`ON ` + ss + `.` + st,
	}
	tgtOn := `ON ` + tableRef("postgres", ts, tt)
	for _, p := range srcOn {
		if strings.Contains(def, p) {
			return strings.Replace(def, p, tgtOn, 1)
		}
	}
	return ""
}

func rewritePGTriggerDef(def, ss, st, ts, tt string) string {
	out := def
	replacements := [][2]string{
		{`ON "` + ss + `"."` + st + `"`, `ON ` + tableRef("postgres", ts, tt)},
		{`ON ` + ss + `."` + st + `"`, `ON ` + tableRef("postgres", ts, tt)},
		{`ON "` + ss + `".` + st, `ON ` + tableRef("postgres", ts, tt)},
		{`ON ` + ss + `.` + st, `ON ` + tableRef("postgres", ts, tt)},
	}
	for _, p := range replacements {
		if strings.Contains(out, p[0]) {
			out = strings.Replace(out, p[0], p[1], 1)
			break
		}
	}
	// 函数 schema 改写：EXECUTE FUNCTION/PROCEDURE schema.fn → 目标 schema
	out = rewriteExecFunctionSchema(out, ss, ts)
	return out
}

var reExecFunc = regexp.MustCompile(`(?i)(EXECUTE\s+(?:FUNCTION|PROCEDURE)\s+)(?:"?([a-zA-Z_][\w$]*)"?\.)?"?([a-zA-Z_][\w$]*)"?`)

func rewriteExecFunctionSchema(def, ss, ts string) string {
	return reExecFunc.ReplaceAllStringFunc(def, func(m string) string {
		sub := reExecFunc.FindStringSubmatch(m)
		if len(sub) < 4 {
			return m
		}
		prefix, schema, name := sub[1], sub[2], sub[3]
		if schema == "" || strings.EqualFold(schema, ss) {
			return prefix + quoteIdent("postgres", ts) + "." + quoteIdent("postgres", name)
		}
		return m
	})
}

func buildPGAlterFixSQL(ctx context.Context, src *sql.DB, ss, ts string, item *TableSchemaDiff) (string, error) {
	ref := tableRef("postgres", ts, item.Table)
	var b strings.Builder
	info, err := fetchPGTableSchemaInfo(ctx, src, ss, item.Table)
	if err != nil {
		return "", err
	}
	colMap := map[string]pgColInfo{}
	for _, c := range info.Columns {
		colMap[strings.ToLower(c.Name)] = c
	}
	conMap := map[string]pgConstraintInfo{}
	for _, c := range info.Constraints {
		conMap[strings.ToLower(c.Name)] = c
	}
	for _, c := range info.ForeignKeys {
		conMap[strings.ToLower(c.Name)] = c
	}
	idxMap := map[string]pgIndexInfo{}
	for _, idx := range info.Indexes {
		idxMap[strings.ToLower(idx.Name)] = idx
	}
	polMap := map[string]pgPolicyInfo{}
	for _, p := range info.Policies {
		polMap[strings.ToLower(p.Name)] = p
	}
	trigMap := map[string]pgTriggerInfo{}
	for _, t := range info.Triggers {
		trigMap[strings.ToLower(t.Name)] = t
	}
	emittedFn := map[string]struct{}{}

	for _, d := range item.Diffs {
		msg := d.Message
		srcOnly := strings.Contains(msg, "仅源")
		differ := strings.Contains(msg, "不一致")
		switch d.Kind {
		case "column":
			if srcOnly {
				c, ok := colMap[strings.ToLower(d.Name)]
				if !ok {
					b.WriteString(fmt.Sprintf("-- 无法解析列 %s 定义\n", d.Name))
					continue
				}
				part := quoteIdent("postgres", c.Name) + " " + c.DataType
				if c.NotNull {
					part += " NOT NULL"
				}
				switch c.Identity {
				case "a":
					part += " GENERATED ALWAYS AS IDENTITY"
				case "d":
					part += " GENERATED BY DEFAULT AS IDENTITY"
				default:
					if c.Default != "" && !strings.Contains(strings.ToLower(c.Default), "nextval(") {
						part += " DEFAULT " + rewriteNextvalSchema(c.Default, ss, ts)
					}
				}
				b.WriteString(fmt.Sprintf("ALTER TABLE %s ADD COLUMN %s;\n", ref, part))
				if c.Identity == "" && strings.Contains(strings.ToLower(c.Default), "nextval(") {
					for _, s := range pgSequenceSetDefaultSQL(ss, ts, item.Table, c.Name, c.Default) {
						b.WriteString(s)
					}
				}
			} else if strings.Contains(msg, "默认值") || strings.Contains(msg, "IDENTITY") {
				c, ok := colMap[strings.ToLower(d.Name)]
				if !ok {
					b.WriteString(fmt.Sprintf("-- 无法解析列 %s 默认值\n", d.Name))
					continue
				}
				writePGColumnDefaultFix(&b, ss, ts, item.Table, c)
			} else if differ {
				b.WriteString(fmt.Sprintf("-- TODO: 列 %s 定义不一致，需人工处理 源=%s 目标=%s\n", d.Name, d.Left, d.Right))
			}
		case "constraint", "foreign_key":
			if srcOnly {
				c, ok := conMap[strings.ToLower(d.Name)]
				if !ok || strings.TrimSpace(c.Def) == "" {
					b.WriteString(fmt.Sprintf("-- 无法解析约束 %s\n", d.Name))
					continue
				}
				b.WriteString(fmt.Sprintf("ALTER TABLE %s ADD CONSTRAINT %s %s;\n",
					ref, quoteIdent("postgres", c.Name), strings.TrimSpace(c.Def)))
			} else if differ {
				b.WriteString(fmt.Sprintf("-- TODO: 约束 %s 定义不一致，需人工处理\n", d.Name))
			}
		case "index":
			if srcOnly {
				idx, ok := idxMap[strings.ToLower(d.Name)]
				if !ok {
					b.WriteString(fmt.Sprintf("-- 无法解析索引 %s\n", d.Name))
					continue
				}
				rewritten := rewritePGIndexDef(idx.Def, ss, item.Table, ts, item.Table)
				if rewritten == "" {
					b.WriteString(fmt.Sprintf("-- 无法改写索引 %s 定义\n", d.Name))
					continue
				}
				b.WriteString(ensureSemi(rewritten) + "\n")
			} else if differ {
				b.WriteString(fmt.Sprintf("-- TODO: 索引 %s 定义不一致，需人工处理\n", d.Name))
			}
		case "comment":
			if srcOnly || differ {
				if d.Name == "" {
					b.WriteString(fmt.Sprintf("COMMENT ON TABLE %s IS %s;\n", ref, quotePGString(d.Left)))
				} else {
					b.WriteString(fmt.Sprintf("COMMENT ON COLUMN %s.%s IS %s;\n",
						ref, quoteIdent("postgres", d.Name), quotePGString(d.Left)))
				}
			}
		case "rls":
			if info.RowSecurity {
				b.WriteString(fmt.Sprintf("ALTER TABLE %s ENABLE ROW LEVEL SECURITY;\n", ref))
			}
			if info.ForceRowSecurity {
				b.WriteString(fmt.Sprintf("ALTER TABLE %s FORCE ROW LEVEL SECURITY;\n", ref))
			}
			if !info.RowSecurity && !info.ForceRowSecurity {
				b.WriteString(fmt.Sprintf("-- 源端未启用 RLS（目标若已启用，不自动 DISABLE）\n"))
			}
		case "policy":
			if srcOnly || differ {
				p, ok := polMap[strings.ToLower(d.Name)]
				if !ok {
					b.WriteString(fmt.Sprintf("-- 无法解析策略 %s\n", d.Name))
					continue
				}
				if differ {
					b.WriteString(fmt.Sprintf("DROP POLICY IF EXISTS %s ON %s;\n", quoteIdent("postgres", p.Name), ref))
				}
				b.WriteString(buildPGCreatePolicySQL(ref, p))
			}
		case "trigger":
			if srcOnly || differ {
				t, ok := trigMap[strings.ToLower(d.Name)]
				if !ok {
					b.WriteString(fmt.Sprintf("-- 无法解析触发器 %s\n", d.Name))
					continue
				}
				if fnSQL, fnKey, err := fetchTriggerFunctionSQL(ctx, src, ss, ts, t.Def); err == nil && fnSQL != "" {
					if _, ok := emittedFn[fnKey]; !ok {
						b.WriteString(fnSQL)
						if !strings.HasSuffix(fnSQL, "\n") {
							b.WriteByte('\n')
						}
						emittedFn[fnKey] = struct{}{}
					}
				}
				if differ {
					b.WriteString(fmt.Sprintf("DROP TRIGGER IF EXISTS %s ON %s;\n", quoteIdent("postgres", t.Name), ref))
				}
				rewritten := rewritePGTriggerDef(t.Def, ss, item.Table, ts, item.Table)
				if rewritten == "" {
					b.WriteString(fmt.Sprintf("-- 无法改写触发器 %s\n", d.Name))
					continue
				}
				b.WriteString(ensureSemi(rewritten) + "\n")
				if t.Enabled == "D" {
					b.WriteString(fmt.Sprintf("ALTER TABLE %s DISABLE TRIGGER %s;\n", ref, quoteIdent("postgres", t.Name)))
				}
			}
		}
	}
	return b.String(), nil
}

func writePGColumnDefaultFix(b *strings.Builder, ss, ts, table string, c pgColInfo) {
	ref := tableRef("postgres", ts, table)
	col := quoteIdent("postgres", c.Name)
	switch c.Identity {
	case "a":
		b.WriteString(fmt.Sprintf("ALTER TABLE %s ALTER COLUMN %s ADD GENERATED ALWAYS AS IDENTITY;\n", ref, col))
		return
	case "d":
		b.WriteString(fmt.Sprintf("ALTER TABLE %s ALTER COLUMN %s ADD GENERATED BY DEFAULT AS IDENTITY;\n", ref, col))
		return
	}
	if c.Default == "" {
		b.WriteString(fmt.Sprintf("-- 源端列 %s 无默认值，不自动 DROP DEFAULT\n", c.Name))
		return
	}
	for _, s := range pgSequenceSetDefaultSQL(ss, ts, table, c.Name, c.Default) {
		b.WriteString(s)
	}
}

func buildPGCreatePolicySQL(tableRef string, p pgPolicyInfo) string {
	perm := "PERMISSIVE"
	if !p.Permissive {
		perm = "RESTRICTIVE"
	}
	roles := p.Roles
	if strings.TrimSpace(roles) == "" {
		roles = "PUBLIC"
	}
	var b strings.Builder
	fmt.Fprintf(&b, "CREATE POLICY %s ON %s AS %s FOR %s TO %s",
		quoteIdent("postgres", p.Name), tableRef, perm, p.Cmd, roles)
	if strings.TrimSpace(p.Qual) != "" {
		fmt.Fprintf(&b, " USING (%s)", p.Qual)
	}
	if strings.TrimSpace(p.WithCheck) != "" {
		fmt.Fprintf(&b, " WITH CHECK (%s)", p.WithCheck)
	}
	b.WriteString(";\n")
	return b.String()
}

func buildPGFunctionFixSQL(ctx context.Context, src *sql.DB, ss, ts string, item *TableSchemaDiff) (string, error) {
	funcs, err := fetchPGSchemaFunctions(ctx, src, ss)
	if err != nil {
		return "", err
	}
	byKey := map[string]pgFunctionInfo{}
	for _, f := range funcs {
		byKey[pgFuncKey(f)] = f
	}
	var b strings.Builder
	for _, d := range item.Diffs {
		if d.Kind != "function" {
			continue
		}
		if !(strings.Contains(d.Message, "仅源") || strings.Contains(d.Message, "不一致")) {
			continue
		}
		// Name 可能是 name(args)
		name := d.Name
		args := ""
		if i := strings.Index(name, "("); i >= 0 {
			args = strings.TrimSuffix(name[i+1:], ")")
			name = name[:i]
		}
		key := strings.ToLower(name) + "(" + strings.ToLower(strings.TrimSpace(args)) + ")"
		f, ok := byKey[key]
		if !ok {
			// 尝试仅按名字匹配
			for k, v := range byKey {
				if strings.HasPrefix(k, strings.ToLower(name)+"(") {
					f, ok = v, true
					break
				}
			}
		}
		if !ok {
			b.WriteString(fmt.Sprintf("-- 无法解析函数 %s\n", d.Name))
			continue
		}
		def := rewriteFunctionDefSchema(f.Definition, ss, ts)
		b.WriteString(ensureSemi(strings.TrimSpace(def)) + "\n\n")
	}
	return b.String(), nil
}

func rewriteFunctionDefSchema(def, ss, ts string) string {
	if ss == ts {
		return def
	}
	// CREATE FUNCTION "ss".name → 目标 schema
	patterns := []string{
		`CREATE OR REPLACE FUNCTION "` + ss + `"`,
		`CREATE FUNCTION "` + ss + `"`,
		`CREATE OR REPLACE FUNCTION ` + ss + `.`,
		`CREATE FUNCTION ` + ss + `.`,
	}
	out := def
	for _, p := range patterns {
		if strings.Contains(out, p) {
			repl := strings.Replace(p, ss, ts, 1)
			out = strings.Replace(out, p, repl, 1)
			break
		}
	}
	return out
}

var reNextval = regexp.MustCompile(`(?i)nextval\s*\(\s*'([^']+)'\s*::\s*regclass\s*\)`)

// pgSequenceBootstrapSQL 若 default 含 nextval，返回建序列+OWNED BY 语句；CREATE TABLE 列上可不带 DEFAULT。
func pgSequenceBootstrapSQL(ss, ts, table, col, def string) (stmts []string, inlineDefault string) {
	if !strings.Contains(strings.ToLower(def), "nextval(") {
		return nil, def
	}
	return pgSequenceSetDefaultSQL(ss, ts, table, col, def), ""
}

func pgSequenceSetDefaultSQL(ss, ts, table, col, def string) []string {
	seqSchema, seqName := parseNextvalSeq(def, ss)
	if seqName == "" {
		// 无法解析则直接改写 schema 后 SET DEFAULT
		return []string{fmt.Sprintf("ALTER TABLE %s ALTER COLUMN %s SET DEFAULT %s;\n",
			tableRef("postgres", ts, table), quoteIdent("postgres", col), rewriteNextvalSchema(def, ss, ts))}
	}
	if seqSchema == ss || seqSchema == "" {
		seqSchema = ts
	}
	seqRef := quoteIdent("postgres", seqSchema) + "." + quoteIdent("postgres", seqName)
	tblRef := tableRef("postgres", ts, table)
	colQ := quoteIdent("postgres", col)
	return []string{
		fmt.Sprintf("CREATE SEQUENCE IF NOT EXISTS %s;\n", seqRef),
		fmt.Sprintf("ALTER TABLE %s ALTER COLUMN %s SET DEFAULT nextval('%s'::regclass);\n",
			tblRef, colQ, strings.ReplaceAll(seqSchema+"."+seqName, "'", "''")),
		fmt.Sprintf("ALTER SEQUENCE %s OWNED BY %s.%s;\n", seqRef, tblRef, colQ),
	}
}

func parseNextvalSeq(def, defaultSchema string) (schema, name string) {
	m := reNextval.FindStringSubmatch(def)
	if len(m) < 2 {
		return "", ""
	}
	raw := strings.Trim(m[1], `"`)
	parts := strings.Split(raw, ".")
	if len(parts) == 2 {
		return strings.Trim(parts[0], `"`), strings.Trim(parts[1], `"`)
	}
	return defaultSchema, strings.Trim(parts[0], `"`)
}

func rewriteNextvalSchema(def, ss, ts string) string {
	if ss == ts {
		return def
	}
	return reNextval.ReplaceAllStringFunc(def, func(m string) string {
		sub := reNextval.FindStringSubmatch(m)
		if len(sub) < 2 {
			return m
		}
		sch, name := parseNextvalSeq(m, ss)
		if sch == ss || sch == "" {
			sch = ts
		}
		return fmt.Sprintf("nextval('%s.%s'::regclass)", sch, name)
	})
}

func fetchTriggerFunctionSQL(ctx context.Context, src *sql.DB, ss, ts, triggerDef string) (sqlText, key string, err error) {
	// 从 trigger def 提取函数名
	sub := reExecFunc.FindStringSubmatch(triggerDef)
	if len(sub) < 4 {
		return "", "", nil
	}
	fnSchema, fnName := sub[2], sub[3]
	if fnSchema == "" {
		fnSchema = ss
	}
	var def string
	err = src.QueryRowContext(ctx, `
SELECT pg_catalog.pg_get_functiondef(p.oid)
FROM pg_proc p
JOIN pg_namespace n ON p.pronamespace = n.oid
WHERE n.nspname = $1 AND p.proname = $2
ORDER BY p.oid
LIMIT 1`, fnSchema, fnName).Scan(&def)
	if err != nil {
		return "", "", err
	}
	key = strings.ToLower(fnSchema + "." + fnName)
	return ensureSemi(strings.TrimSpace(rewriteFunctionDefSchema(def, ss, ts))) + "\n", key, nil
}

func quotePGString(s string) string {
	return "'" + strings.ReplaceAll(s, "'", "''") + "'"
}

func ensureSemi(s string) string {
	s = strings.TrimSpace(s)
	if s == "" {
		return s
	}
	if !strings.HasSuffix(s, ";") {
		return s + ";"
	}
	return s
}

func buildMySQLCreateTableSQL(ctx context.Context, src *sql.DB, table string) (string, error) {
	var tbl, ddl string
	err := src.QueryRowContext(ctx, "SHOW CREATE TABLE `"+strings.ReplaceAll(table, "`", "``")+"`").Scan(&tbl, &ddl)
	if err != nil {
		return "", err
	}
	if !strings.HasSuffix(strings.TrimSpace(ddl), ";") {
		ddl = strings.TrimSpace(ddl) + ";"
	}
	var b strings.Builder
	b.WriteString(ddl + "\n")
	// 附带触发器（SHOW CREATE TABLE 不含触发器）
	trigs, err := fetchMySQLTriggers(ctx, src, table)
	if err == nil {
		for _, t := range trigs {
			sqlText := strings.TrimSpace(t.CreateSQL)
			if sqlText == "" {
				continue
			}
			if !strings.HasSuffix(sqlText, ";") {
				sqlText += ";"
			}
			b.WriteString(sqlText + "\n")
		}
	}
	return b.String(), nil
}

func quoteMySQLDefault(v, typ string) string {
	upper := strings.ToUpper(typ)
	if strings.Contains(upper, "INT") || strings.Contains(upper, "DECIMAL") || strings.Contains(upper, "FLOAT") || strings.Contains(upper, "DOUBLE") || strings.Contains(upper, "BIT") {
		return v
	}
	if strings.EqualFold(v, "CURRENT_TIMESTAMP") || strings.HasPrefix(strings.ToUpper(v), "CURRENT_TIMESTAMP") {
		return v
	}
	if strings.EqualFold(v, "NULL") {
		return "NULL"
	}
	return "'" + strings.ReplaceAll(v, "'", "''") + "'"
}
